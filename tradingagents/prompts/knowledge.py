def apply_knowledge_snippet(key: str, prompt: str, config: Mapping[str, Any] | None = None) -> str:
    """Append a role-specific knowledge snippet when enabled."""

    if not _enabled(config):
        return prompt
    snippet = ZH_KNOWLEDGE_SNIPPETS.get(key)
    if not snippet:
        return prompt
    return f"{prompt.rstrip()}{snippet}"
